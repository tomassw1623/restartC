#include <stdio.h>

int main(void) {
    // [하는 일]
    // 정수 5개를 입력받아 합과 평균을 출력한다.

    int arr[5];        // 정수 5개를 담을 "칸 5개" (arr[0]~arr[4])
    int sum = 0;       // 합계는 0부터 시작해야 계속 더할 수 있다.
    int i;             // 반복문에서 사용할 번호표

    printf("정수 5개 입력: ");

    for (i = 0; i < 5; i++) {
        // scanf는 "값을 저장할 장소의 주소"가 필요하다.
        // arr[i]는 i번째 칸의 값, &arr[i]는 i번째 칸의 주소
        scanf("%d", &arr[i]);
        sum += arr[i]; // 입력받은 값을 합계에 누적
    }

    // 평균은 소수점이 나올 수 있으므로 실수로 계산해야 한다.
    // 5로 나누면 정수 나눗셈(소수점 버림)이 되니까 5.0으로 나눈다.
    printf("합=%d, 평균=%.2f\n", sum, sum / 5.0);

    return 0;
}
